package bot

// helpText — ответ на кнопку «🆘 Помощь». Отправляется в старом Markdown
// Telegram: жирный — одной звёздочкой, непарные * _ ` [ ломают отправку
// целиком (Telegram отвечает 400, человек не получает ничего).
//
// Основной путь — ссылка на отдельный сервер: адрес авто-подключения из
// России пока открывается не у всех, поэтому оно описано как запасное.
const helpText = `📖 *Как подключиться*

Приложение — *Happ*. Оно есть для iPhone, Android, Windows, Mac и Linux.

*1. Установите Happ*
• iPhone, iPad — App Store
• Android — Google Play
• Windows, Mac, Linux — сайт happ.su (там же ссылки для всех устройств)

*2. Возьмите ссылку в боте*
Нажмите «🔑 Подключиться», затем кнопку 🔗 с названием сервера. Бот пришлёт ссылку — нажмите на неё, и она скопируется.

*3. Добавьте ссылку в Happ*
Откройте Happ, нажмите «+» вверху и выберите вставку из буфера обмена. Сервер появится в списке.

*4. Включите VPN*
Нажмите большую круглую кнопку. В первый раз устройство спросит разрешение на VPN — разрешите.

*Второе устройство*
Кнопка 📷 рядом с сервером показывает QR-код. В Happ нажмите «+», выберите сканирование QR-кода и наведите камеру на экран.

*Авто-подключение*
Кнопка «⭐ Авто-подключение» даёт одну ссылку сразу на все серверы, добавляется она так же. Если Happ её не загрузил — пользуйтесь ссылками на отдельные серверы.

*Не работает?*
Выберите в Happ другой сервер или возьмите в боте ссылку на другой. Не помогло — напишите администратору.`
